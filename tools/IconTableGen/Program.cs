// Outil ponctuel : lit les ligatures (GSUB) et la table cmap du TTF Material Symbols,
// puis génère src/StdMachine.Hmi/Controls/IconCodes.g.cs pour les icônes listées dans icons.txt.
// Usage : IconTableGen <MaterialSymbolsOutlined.ttf> <icons.txt> <sortie.cs>
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

static class Program
{
    static byte[] d;
    static int U16(int o) { return (d[o] << 8) | d[o + 1]; }
    static int S16(int o) { return (short)U16(o); }
    static long U32(int o) { return ((long)U16(o) << 16) | (uint)U16(o + 2); }

    static int Main(string[] a)
    {
        d = File.ReadAllBytes(a[0]);
        var wanted = File.ReadAllLines(a[1]).Select(l => l.Trim()).Where(l => l.Length > 0 && l[0] != '#').Distinct().ToList();
        int numTables = U16(4);
        var tables = new Dictionary<string, int>();
        for (int i = 0; i < numTables; i++)
        {
            int r = 12 + i * 16;
            tables[Encoding.ASCII.GetString(d, r, 4)] = (int)U32(r + 8);
        }
        var cmap = ReadCmap(tables["cmap"]);              // point de code -> glyphe
        var glyphToCp = new Dictionary<int, int>();       // glyphe -> plus petit point de code PUA
        foreach (var kv in cmap)
        {
            int cp = kv.Key, g = kv.Value;
            int old;
            if (!glyphToCp.TryGetValue(g, out old) || (cp >= 0xE000 && (old < 0xE000 || cp < old))) glyphToCp[g] = cp;
        }
        var glyphToChar = new Dictionary<int, char>();
        foreach (var kv in cmap) if (kv.Key < 128 && !glyphToChar.ContainsKey(kv.Value)) glyphToChar[kv.Value] = (char)kv.Key;

        var ligs = ReadLigatures(tables["GSUB"], glyphToChar);  // nom -> glyphe
        Console.WriteLine("Ligatures lues : " + ligs.Count);
        if (a.Length > 3) File.WriteAllLines(a[3], ligs.Select(kv => kv.Key + " " + kv.Value + " " + (glyphToCp.ContainsKey(kv.Value) ? glyphToCp[kv.Value].ToString("X") : "-")));
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> par tools/IconTableGen depuis MaterialSymbolsOutlined.ttf. Ne pas modifier. </auto-generated>");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();
        sb.AppendLine("namespace StdMachine.Hmi.Controls");
        sb.AppendLine("{");
        sb.AppendLine("    internal static class IconCodes");
        sb.AppendLine("    {");
        sb.AppendLine("        public static readonly Dictionary<string, int> Map = new Dictionary<string, int>");
        sb.AppendLine("        {");
        int missing = 0;
        foreach (var n in wanted.OrderBy(x => x, StringComparer.Ordinal))
        {
            int g, cp;
            if (ligs.TryGetValue(n, out g) && glyphToCp.TryGetValue(g, out cp))
                sb.AppendLine("            [\"" + n + "\"] = 0x" + cp.ToString("X4") + ",");
            else { Console.WriteLine("MANQUANT : " + n); missing++; }
        }
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        File.WriteAllText(a[2], sb.ToString(), new UTF8Encoding(true));
        Console.WriteLine("Écrit " + (wanted.Count - missing) + " icônes, " + missing + " manquantes.");
        return missing == 0 ? 0 : 2;
    }

    static Dictionary<int, int> ReadCmap(int t)
    {
        int n = U16(t + 2);
        int best = -1, bestScore = -1;
        for (int i = 0; i < n; i++)
        {
            int r = t + 4 + i * 8;
            int plat = U16(r), enc = U16(r + 2);
            int score = plat == 3 && enc == 10 ? 3 : plat == 0 && enc >= 4 ? 3 : plat == 3 && enc == 1 ? 2 : plat == 0 ? 1 : 0;
            if (score > bestScore) { bestScore = score; best = t + (int)U32(r + 4); }
        }
        var map = new Dictionary<int, int>();
        int fmt = U16(best);
        if (fmt == 12)
        {
            long groups = U32(best + 12);
            for (int i = 0; i < groups; i++)
            {
                int g = best + 16 + i * 12;
                long s = U32(g), e = U32(g + 4), gid = U32(g + 8);
                for (long c = s; c <= e; c++) map[(int)c] = (int)(gid + (c - s));
            }
        }
        else if (fmt == 4)
        {
            int segX2 = U16(best + 6), seg = segX2 / 2;
            int endO = best + 14, startO = endO + segX2 + 2, deltaO = startO + segX2, rangeO = deltaO + segX2;
            for (int i = 0; i < seg; i++)
            {
                int end = U16(endO + i * 2), start = U16(startO + i * 2), delta = S16(deltaO + i * 2), ro = U16(rangeO + i * 2);
                for (int c = start; c <= end && c != 0xFFFF; c++)
                {
                    int gid;
                    if (ro == 0) gid = (c + delta) & 0xFFFF;
                    else { int p = rangeO + i * 2 + ro + (c - start) * 2; gid = U16(p); if (gid != 0) gid = (gid + delta) & 0xFFFF; }
                    if (gid != 0) map[c] = gid;
                }
            }
        }
        else throw new Exception("cmap format " + fmt + " non géré");
        return map;
    }

    static List<int> Coverage(int o)
    {
        var l = new List<int>();
        int fmt = U16(o);
        int n = U16(o + 2);
        if (fmt == 1) { for (int i = 0; i < n; i++) l.Add(U16(o + 4 + i * 2)); }
        else
        {
            for (int i = 0; i < n; i++)
            {
                int r = o + 4 + i * 6; int s = U16(r), e = U16(r + 2);
                for (int g = s; g <= e; g++) l.Add(g);
            }
        }
        return l;
    }

    static Dictionary<string, int> ReadLigatures(int gsub, Dictionary<int, char> g2c)
    {
        var res = new Dictionary<string, int>();
        int lookupList = gsub + U16(gsub + 8);
        int count = U16(lookupList);
        for (int i = 0; i < count; i++)
        {
            int lk = lookupList + U16(lookupList + 2 + i * 2);
            int type = U16(lk), sub = U16(lk + 4);
            for (int s = 0; s < sub; s++)
            {
                int st = lk + U16(lk + 6 + s * 2);
                int t = type;
                if (t == 7) { t = U16(st + 2); st = st + (int)U32(st + 4); }
                if (t != 4) continue;
                var cov = Coverage(st + U16(st + 2));
                int setCount = U16(st + 4);
                for (int k = 0; k < setCount; k++)
                {
                    int set = st + U16(st + 6 + k * 2);
                    int lc = U16(set);
                    for (int m = 0; m < lc; m++)
                    {
                        int lg = set + U16(set + 2 + m * 2);
                        int glyph = U16(lg), comps = U16(lg + 2);
                        var chars = new StringBuilder();
                        char c0;
                        bool ok = g2c.TryGetValue(cov[k], out c0);
                        if (ok) chars.Append(c0);
                        for (int q = 0; q < comps - 1 && ok; q++)
                        {
                            char c;
                            if (g2c.TryGetValue(U16(lg + 4 + q * 2), out c)) chars.Append(c); else ok = false;
                        }
                        string name = chars.ToString().ToLowerInvariant();
                        if (ok && !res.ContainsKey(name)) res[name] = glyph;
                    }
                }
            }
        }
        return res;
    }
}
